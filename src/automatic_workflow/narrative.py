"""Narrative CSV serialization helpers."""

from __future__ import annotations

from automatic_workflow.csv_utils import build_csv_text
from automatic_workflow.text import normalize_title


def fill_missing_titles(titles: list[str], paragraphs: list[str]) -> list[str]:
    """Return one non-empty title per paragraph.

    Args:
        titles: Candidate titles, often generated by an LLM.
        paragraphs: Narrative paragraphs.

    Returns:
        A list of titles with `event-N` fallbacks.
    """

    final_titles: list[str] = []
    for index, _paragraph in enumerate(paragraphs, start=1):
        title = normalize_title(titles[index - 1]) if index - 1 < len(titles) else ""
        final_titles.append(title or f"event-{index}")
    return final_titles


def serialize_story_text(paragraphs: list[str], titles: list[str] | None = None) -> str:
    """Serialize paragraphs and optional titles to narrative CSV text."""

    actual_titles = fill_missing_titles(titles or [], paragraphs)
    rows = [["title", "description"]]
    rows.extend(
        [title, paragraph] for title, paragraph in zip(actual_titles, paragraphs, strict=True)
    )
    return build_csv_text(rows)
